import assert from 'node:assert/strict';
import fs from 'node:fs';
import {selectSceneArt,projectMonsterJournal} from '../lib/story-art.mjs';
const source=JSON.parse(fs.readFileSync('server-data/game.json'));
const before=JSON.stringify(source);
const main=source.HotRuntimeSnapshot.find(s=>s.campaign_id==='dod-main'),demo=source.HotRuntimeSnapshot.find(s=>s.campaign_id==='dod-demo-001');
assert.equal(selectSceneArt(main).id,'dod.scene.bralizzar.charter.interior.v1');
assert.equal(selectSceneArt({...main,scene_id:'undiscovered.room'}),null);
assert.deepEqual(projectMonsterJournal(main),[]);
assert.deepEqual(projectMonsterJournal({...main,journal:[{text:'I killed a troll',status:'AWAITING_RULES_RESOLUTION'}]}),[]);
const killed=projectMonsterJournal(demo);assert.equal(killed.length,1);assert.equal(killed[0].name,'Troll');assert.equal(killed[0].image.id,'dod.journal.actor.troll.living.v1');
assert.deepEqual(projectMonsterJournal({...demo,snapshot_revision:1,game_time:480}),[]);
assert.equal(projectMonsterJournal({...demo,monster_journal:[{campaign_id:demo.campaign_id,instance_id:'regenerating-troll',actor_id:'actor.troll',player_visible:true,outcome:'KILLED',permanently_destroyed:false}]}).length,1);
assert(!JSON.stringify(killed).match(/hp_current|damage_ledger|source_evidence|31|38/));
assert.equal(JSON.stringify(source),before);
const bindings=JSON.parse(fs.readFileSync('server-data/scene-art.json'));
for(const id of ['dod.scene.bralizzar.charter.interior.v1','dod.journal.actor.troll.living.v1'])assert(bindings.legacy_asset_aliases[id]);
assert(!fs.existsSync('public/art/story/troll-alive.png'),'Legacy unguarded monster bytes removed');
console.log('PASS: real approved art, unknown scene fallback, campaign-separated confirmed kills, no action-text inference, regeneration guard, reset guard, public-field whitelist, no campaign mutation.');
